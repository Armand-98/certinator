"""Regenerate src/certinator/suffixes.py from the Public Suffix List.

Run by hand when the list moves. The generated module is committed so that the
tool needs no network at import and two runs a year apart agree on what
"foo.co.uk" means.

Only the ICANN section is kept. The private section records delegations a
company made inside a domain it owns (github.io, s3.amazonaws.com), and for
brand impersonation those are the interesting part of the name rather than a
boundary to hide it behind: paypal-login.github.io is the brand sitting as a
label under someone else's registrable domain, which is exactly what the
subdomain technique is meant to catch.

Rules arrive as unicode. A certificate carries the punycode form, so both
spellings of every rule are written out and the lookup needs no decoder.
"""

from __future__ import annotations

import argparse
import datetime
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from certinator.tls import context  # noqa: E402

URL = "https://publicsuffix.org/list/public_suffix_list.dat"
OUT = ROOT / "src" / "certinator" / "suffixes.py"

BEGIN = "// ===BEGIN ICANN DOMAINS==="
END = "// ===END ICANN DOMAINS==="

# The list is around 350 KB; anything an order of magnitude past that is not
# the list, and this reads the whole body into memory.
MAX_BYTES = 8 << 20

HEADER = '''"""Public suffix rules, generated by tools/build_suffixes.py. Do not edit.

Source: {url}
ICANN section only, retrieved {date}: {ordinary} rules, {wildcard} wildcards,
{exception} exceptions. Rules are stored in both unicode and punycode form so a
name taken off a certificate matches without being decoded first.
"""

ORDINARY = frozenset("""{ordinary_text}""".split("\\n"))

# "*.ck" matches any single label in front of the parent stored here.
WILDCARD = frozenset("""{wildcard_text}""".split("\\n"))

# "!www.ck" overrides the wildcard: the rule itself is not a public suffix.
EXCEPTION = frozenset("""{exception_text}""".split("\\n"))
'''


def fetch(url: str) -> str:
    with urllib.request.urlopen(url, context=context(), timeout=60) as response:
        body = response.read(MAX_BYTES + 1)
    if len(body) > MAX_BYTES:
        raise SystemExit(f"{url} returned more than {MAX_BYTES} bytes")
    return body.decode("utf-8")


def icann_rules(text: str) -> list[str]:
    inside = False
    rules = []
    for line in text.splitlines():
        line = line.strip()
        if line == BEGIN:
            inside = True
            continue
        if line == END:
            break
        if not inside or not line or line.startswith("//"):
            continue
        rules.append(line.split()[0].lower())
    if not inside:
        raise SystemExit("no ICANN section found in the list")
    return rules


def ace(rule: str) -> str:
    """The punycode spelling of a rule, or the rule if it is already ASCII."""
    labels = []
    for label in rule.split("."):
        try:
            label.encode("ascii")
        except UnicodeEncodeError:
            label = "xn--" + label.encode("punycode").decode("ascii")
        labels.append(label)
    return ".".join(labels)


def classify(rules: list[str]) -> tuple[set[str], set[str], set[str]]:
    ordinary: set[str] = set()
    wildcard: set[str] = set()
    exception: set[str] = set()
    for rule in rules:
        if rule.startswith("!"):
            target, rule = exception, rule[1:]
        elif rule.startswith("*."):
            # Stored as the parent, so a lookup tests the labels to its right.
            target, rule = wildcard, rule[2:]
        elif "*" in rule:
            # Wildcards elsewhere in a rule have never appeared and are not
            # implemented; failing loudly beats silently mismatching.
            raise SystemExit(f"unsupported wildcard rule {rule!r}")
        else:
            target = ordinary
        if not rule:
            continue
        target.add(rule)
        target.add(ace(rule))
    return ordinary, wildcard, exception


def render(ordinary: set[str], wildcard: set[str], exception: set[str]) -> str:
    return HEADER.format(
        url=URL,
        date=datetime.date.today().isoformat(),
        ordinary=len(ordinary), wildcard=len(wildcard), exception=len(exception),
        ordinary_text="\n".join(sorted(ordinary)),
        wildcard_text="\n".join(sorted(wildcard)),
        exception_text="\n".join(sorted(exception)),
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--url", default=URL)
    parser.add_argument("--from-file", type=Path,
                        help="read the list from disk instead of fetching it")
    parser.add_argument("--out", type=Path, default=OUT)
    args = parser.parse_args()

    text = (args.from_file.read_text("utf-8") if args.from_file
            else fetch(args.url))
    ordinary, wildcard, exception = classify(icann_rules(text))
    if len(ordinary) < 1000:
        raise SystemExit(f"only {len(ordinary)} rules parsed, refusing to write")
    args.out.write_text(render(ordinary, wildcard, exception), "utf-8")
    print(f"{args.out}: {len(ordinary)} rules, {len(wildcard)} wildcards, "
          f"{len(exception)} exceptions")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
